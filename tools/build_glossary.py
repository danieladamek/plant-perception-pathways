#!/usr/bin/env python3
"""build_glossary.py — Plant Perception Pathways (Cowork, 2026-11-24). content-pack/glossary.yaml from source/glossary/.
Sources: written.yaml (pack conventions), methods.yaml (copied from PPE), picks.yaml + notes/research/glossary-harvest.json
(GO/ChEBI records via OLS4, verbatim), and the Plant Ontology records already quoted in content-pack/anatomy.yaml.
A term with no usable record is left out and listed. Obsolete records and editor notes are refused.
Each term listed in a 101's `terms` gets that concept (fewest prerequisites first). Usage (app folder): python3 tools/build_glossary.py"""
import glob, json, re, yaml
from collections import Counter
T = yaml.safe_load(open("source/glossary/terms.yaml", encoding="utf-8"))
W = yaml.safe_load(open("source/glossary/written.yaml", encoding="utf-8"))["pack"]
M = yaml.safe_load(open("source/glossary/methods.yaml", encoding="utf-8"))
P = yaml.safe_load(open("source/glossary/picks.yaml", encoding="utf-8"))
H = json.load(open("notes/research/glossary-harvest.json", encoding="utf-8"))
A = yaml.safe_load(open("content-pack/anatomy.yaml", encoding="utf-8"))
slug = lambda s: re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
EDIT = re.compile(r"Editor no(te|de)|Currently this class|we may want|^TODO|this term was obsoleted|^See also|^Note that|^Note:", re.I)
TAG = re.compile(r"</?(i|em|small|sub|sup|b)>")   # ChEBI markup; removing the tags keeps the words verbatim
fms = [yaml.safe_load(open(f, encoding="utf-8").read().split("---")[1]) or {} for f in sorted(glob.glob("content-pack/concepts/*.md"))]
depth = {}
def d(cid):
    if cid not in depth:
        fm = next((x for x in fms if x["id"] == cid), {}); depth[cid] = 0
        depth[cid] = 1 + max([d(q) for q in fm.get("prerequisites") or []], default=-1)
    return depth[cid]
CONCEPT = {}
for fm in sorted(fms, key=lambda x: (d(x["id"]), x["id"])):
    for tid in fm.get("terms") or []: CONCEPT.setdefault(tid, fm["id"])
def first_sentence(s):
    m = re.match(r"(.+?\.)(\s|$)", s); s = m.group(1) if m else s
    return s if len(s) <= 200 else s[:197].rsplit(" ", 1)[0] + "…"
out, left = [], []
for t in T["notation"]:
    w = W[t["term"]]
    out.append({"id": slug(t["term"]), "term": t["term"], "kind": "notation", "variants": t.get("variants") or [],
                "short": w["short"], "definition": "<!-- framing -->" + w["definition"], "basis": "app convention"})
for g in M:
    e = dict(g); e["id"] = slug(e["term"]); e["kind"] = "methods"; out.append(e)
for t in T["science"]:
    oid = P.get(t["term"]); r = H.get(oid or "", {})
    defs = [TAG.sub("", x) for x in (r.get("definitions") or []) if x and not EDIT.search(x)]
    if not r.get("found") or r.get("obsolete") or (r.get("label") or "").startswith("obsolete") or not defs:
        left.append(t["term"]); continue
    out.append({"id": slug(t["term"]), "term": t["term"], "kind": "science", "variants": t.get("variants") or [],
                "short": first_sentence(defs[0]), "definition": defs[0], "basis": "ontology, verbatim",
                "definition_source": {"id": oid, "label": r["label"], "source": r["source"], "retrieved_on": r["retrieved_on"],
                                      "mapping": "exact label" if r["label"].lower() == t["term"].lower() else f"curator mapping from '{t['term']}'"}})
seen = {e["id"] for e in out}
for v in A["values"]:                       # Plant Ontology terms already quoted for anatomy (verbatim, attributed)
    for tm in v["terms"]:
        if not tm.get("definition") or not tm.get("id", "").startswith("PO:"): continue
        e_id = slug(tm["label"])
        if e_id in seen: continue
        seen.add(e_id)
        out.append({"id": e_id, "term": tm["label"][0].upper() + tm["label"][1:], "kind": "science",
                    "variants": [s for s in (tm.get("synonyms") or []) if len(s) > 3 and s.lower() != tm["label"].lower()][:4],
                    "short": first_sentence(tm["definition"]), "definition": tm["definition"], "basis": "ontology, verbatim",
                    "definition_source": {"id": tm["id"], "label": tm["label"], "source": tm["source"], "retrieved_on": tm["retrieved_on"],
                                          "mapping": "exact label"}})
for e in out:
    if e["id"] in CONCEPT: e["concept"] = CONCEPT[e["id"]]
# variants must not collide with another term or variant (whole-word, case-insensitive)
names = Counter(x.lower() for e in out for x in [e["term"], *e["variants"]])
for e in out: e["variants"] = [v for v in e["variants"] if names[v.lower()] == 1]
missing = sorted({tid for fm in fms for tid in fm.get("terms") or []} - {e["id"] for e in out})
hdr = ("# glossary.yaml — generated by tools/build_glossary.py from source/glossary/ and anatomy.yaml. Do not edit by hand.\n"
       "# basis: 'ontology, verbatim' = quoted from the named record (UI-31); 'app convention' = the app's own notation.\n")
open("content-pack/glossary.yaml", "w", encoding="utf-8").write(hdr + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=120))
print(f"glossary: {len(out)} terms · {dict(Counter((e['kind'], e['basis']) for e in out))} · left out {left} · concept terms missing {missing}")
