#!/usr/bin/env python3
"""assemble_pack.py — Plant Perception Pathways: build the perception layer of content-pack/ from source/.
Cowork-side tool (Actualizer, 2026-11-19), modelled on PPE's tools/assemble_pack.py. Deterministic: same inputs → same bytes.

Usage: python3 tools/assemble_pack.py      (run from the app folder, after verify_refs.py and export_handoff.py)

Inputs  source/data/paths.json (curated rows, exported by export_handoff.py), source/data/tree.json, source/data/key.json,
        source/data/references.json (verify_refs.py), source/literature.json (raw harvest, for authors), source/data/about-framing.json
Outputs content-pack/paths.yaml, hierarchy.yaml, legend.yaml, references.yaml, context-note.md
Rules (content-pack/app-methods.md §1 is normative):
  1. Fields are copied one for one from the curated rows; null stays null. The curation's `transducer` column becomes the
     `receptor` stage field (the plant stage kind); `transducer_tier` keeps its generic name.
  2. The script only ADDS: provenance_words, contested_fields (fields whose text holds ⚑), refs (reference numbers,
     resolved from each row's key_citation list — never from reading text).
  3. Only rows with row_status curated are written. Dropped rows and About-page framing stay in source/ for the record.
"""
import json, os, re, yaml

SRC, OUT = "source", "content-pack"
J = lambda f: json.load(open(os.path.join(SRC, "data", f), encoding="utf-8"))
PROV = {"A": "quoted or closely tracked from a verified abstract", "K": "curator expert knowledge, unverified"}
STAGES = ["stimulus", "receptor", "cascade", "signal_route", "integration", "response"]

def dump(name, data, header):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(header.rstrip() + "\n")
        yaml.safe_dump(data, f, allow_unicode=True, sort_keys=False, width=120)

# ── references: numbered in first-citation order along the paths, then the rest alphabetically
rows = [r for r in J("paths.json") if r["row_status"] == "curated"]
refs_src = {r["id"]: r for r in J("references.json")["references"]}
lit = {w["id"]: w for w in json.load(open(os.path.join(SRC, "literature.json"), encoding="utf-8"))["works"]}
order = []
for r in rows:
    for k in r["key_citation"]:
        if k not in order: order.append(k)
framing = J("about-framing.json")
for f in framing:
    for k in f.get("key_citation") or []:
        if k not in order: order.append(k)
order += sorted(k for k in refs_src if k not in order)
N = {k: i + 1 for i, k in enumerate(order)}

def cite(k):
    w, r = lit.get(k, {}), refs_src[k]
    au = w.get("authors") or []
    surname = (au[0].split()[-1] if au else "Anonymous")
    who = surname + (" et al." if len(au) > 2 else (f" & {au[1].split()[-1]}" if len(au) == 2 else ""))
    title = re.sub(r"<[^>]+>", "", r.get("title") or "").rstrip(".")
    return f"{who} {r.get('year')}. {title}. {r.get('venue') or ''}".strip()

# tier (validate_pack): reviews and position papers → background; primary research → current. Promoting landmark papers to
# seminal/classic needs a summary and is left to the curator (todo).
BACKGROUND = {"casal2013_shade_review", "chen2011_phy_review", "chaves2011_cry_review", "yi2005_cop1", "jones2006_immune", "hart2021_phot_review",
              "morita2010_gravity_review", "taiz2019_consciousness", "calvo2020_intelligent", "wang2006_myc_distribution"}
NO_ABSTRACT_NOTE = {"wang2006_myc_distribution": "No abstract in OpenAlex or Europe PMC (checked 2026-11-19); cited by no path; kept as a bibliography record only."}
references = []
for k in order:
    r = refs_src[k]
    rec = {"key": k, "citation": cite(k), "year": r.get("year"), "tier": "background" if k in BACKGROUND else "current", "doi": r["doi"], "url": f"https://doi.org/{r['doi']}",
           "pmid": r.get("pmid"), "verified": r["verified"], "verified_how": r["verified_how"]}
    if r.get("verified_via"): rec["verified_via"] = r["verified_via"]
    if r["verified"] and r.get("abstract"):
        rec.update(abstract=r["abstract"], abstract_source=r["abstract_source"], harvested_on=r.get("harvested_on"))
    if k in NO_ABSTRACT_NOTE: rec["abstract_note"] = NO_ABSTRACT_NOTE[k]
    rec["cited_by_paths"] = [p["path_id"] for p in rows if k in p["key_citation"]]
    rec["n"] = N[k]
    references.append(rec)
dump("references.yaml", references,
     "# references.yaml — generated by tools/assemble_pack.py from source/data/references.json (tools/verify_refs.py).\n"
     "# verified = OpenAlex (or, where OpenAlex's title is defective, Europe PMC) title matches the expected title, ratio ≥ 0.85.\n"
     "# Abstracts are verbatim and attached only to verified records. n is the number shown as [n].")

# ── paths
paths = []
for r in rows:
    p = {}
    for k, v in r.items():
        if k == "transducer": k = "receptor"
        if k in ("key_citation",): v = "; ".join(v) if v else None
        if k == "also_in": continue
        p[k] = v
    p["also_in"] = r.get("also_in") or []
    p["provenance_words"] = [PROV[c] for c in re.split(r"\s*,\s*", r.get("provenance") or "") if c in PROV]
    p["contested_fields"] = [k for k, v in p.items() if isinstance(v, str) and "⚑" in v]
    p["refs"] = [N[k] for k in r["key_citation"]]
    paths.append(p)
dump("paths.yaml", {"paths": paths},
     f"# paths.yaml — {len(paths)} curated plant perception pathways, stimulus → response. Copied field for field from\n"
     "# source/curation/paths.yaml (Cowork drafts from verified abstracts; curated by Daniel 2026-11-18/19, decisions.yaml)\n"
     "# by tools/assemble_pack.py. null = no harvested source supports that stage yet (gap). Edit source/, then re-run.")

# ── hierarchy
tree = J("tree.json")
for b in tree["children"]:   # the candidate-senses branch is marked for the core (K39 item 10)
    if b["name"].startswith("Candidate senses"): b["contested"] = True; b["badge"] = "candidate sense — not established"
dump("hierarchy.yaml", {"tree": tree},
     "# hierarchy.yaml — the plant perception tree, one of several valid divisions. A leaf marked dual: true lists a\n"
     "# path that also belongs to another branch (⚑ dual membership).")

# ── legend (outside-reader rows only)
legend = [x for x in J("key.json") if x["item"] not in ("What this is",)]
legend.insert(0, {"item": "What this is", "meaning": "Curated pathways of plant perception — how plants sense their surroundings and "
                  "their own state, from stimulus to receptor to response — each stage tied to a verified published abstract."})
dump("legend.yaml", {"legend": legend}, "# legend.yaml — codes, tiers and flags, for outside readers.")

# ── context note (About page): scope + the framing entries, cited [n]
f0 = framing[0]
note = f"""# About these pathways

**What "perception" means here.** In plant biology, *perception* means the detection of a signal by a receptor and
its transduction into a response. Every pathway here is read that way: stimulus → receptor → cascade → signal route →
integration → response. Blank stages are gaps — no verified source supports them yet — not claims that nothing is there.

**Organism.** *Arabidopsis thaliana* first. Senses that Arabidopsis lacks, such as root-nodule symbiosis, are included
with their evidence species named on the row.

**Candidate senses.** A separate group holds claims that are disputed or rest on a single study (sound, vibration,
kin recognition, magnetic fields, learning). Each shows the claim and, where one exists, the evidence against it.

## Is this perception? Two views

Whether plants are conscious or intelligent is a separate question from whether they perceive in the sense above,
and this app does not answer it. Two published positions:

- **Against:** {f0['hypothesis_group'].split('AGAINST ')[1].split('. FOR')[0].replace('taiz2019', f'[{N["taiz2019_consciousness"]}]')}.
- **For:** {f0['hypothesis_group'].split('FOR ')[1].split('. The app')[0].replace('calvo2020', f'[{N["calvo2020_intelligent"]}]')}.
"""
open(os.path.join(OUT, "context-note.md"), "w", encoding="utf-8").write(note)
print(f"paths {len(paths)} · references {len(references)} (cited {len({k for r in rows for k in r['key_citation']})}) · branches {len(tree['children'])}")
