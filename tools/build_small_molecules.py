#!/usr/bin/env python3
"""build_small_molecules.py — content-pack/small-molecules.yaml from the PubChem harvest (app-methods.md §10).
Cowork-side tool, 2026-11-17; plant copy 2026-11-19 (plant path ids PL01…; chromophores stay visible). Deterministic. Merges seed entries that resolve to the same InChIKey."""
import json, os, yaml, hashlib, collections
seed = {m["id"]: m for m in yaml.safe_load(open("source/small-molecules-seed.yaml", encoding="utf-8"))["molecules"]}
harv = json.load(open("notes/research/small-molecules-harvest.json", encoding="utf-8"))["molecules"]
inter = yaml.safe_load(open("content-pack/interactions.yaml", encoding="utf-8"))["interactions"]
mols = yaml.safe_load(open("content-pack/molecules.yaml", encoding="utf-8"))["molecules"]
paths = {p["path_id"] for p in yaml.safe_load(open("content-pack/paths.yaml", encoding="utf-8"))["paths"]}
# which macromolecule each bundled structure belongs to (binding partners)
owner = collections.defaultdict(set)
for s in yaml.safe_load(open("content-pack/structures.yaml", encoding="utf-8"))["structures"]:
    for m in s["molecules"]: owner[s["id"]].add(m)
groups, missing = collections.OrderedDict(), []
for h in harv:
    s = seed[h["id"]]
    if not h["found"]: missing.append({"id": h["id"], "query": h["query"], "why": s.get("why") or s.get("name_as_recorded")}); continue
    key = h["pubchem"]["InChIKey"].split("-")[0]       # connectivity block: stereo and protonation forms share one sheet
    g = groups.setdefault(key, {"id": f"CID{h['pubchem']['CID']}", "pubchem": h["pubchem"], "retrieved_on": h["retrieved_on"],
                                "conformer": h.get("conformer"), "file": f"structures/small/{h['file']}" if h.get("file") else None,
                                "sha256": h.get("sha256"), "forms": [], "classes": [], "sources": [], "ccd": [], "bound_in": [], "paths": [], "interactions": []})
    form = {"cid": h["pubchem"]["CID"], "title": h["pubchem"].get("Title"), "inchikey": h["pubchem"]["InChIKey"],
            "conformer": h.get("conformer"), "file": f"structures/small/{h['file']}" if h.get("file") else None, "sha256": h.get("sha256"),
            "source": h["pubchem"]["source"]}
    if form["cid"] not in [f["cid"] for f in g["forms"]]: g["forms"].append(form)
    if g["conformer"] != "3d" and h.get("conformer") == "3d":   # prefer a form with a 3D conformer as the sheet's default view
        g.update(id=f"CID{form['cid']}", pubchem=h["pubchem"], conformer="3d", file=form["file"], sha256=form["sha256"])
    if s["class"] not in g["classes"]: g["classes"].append(s["class"])
    if s.get("ccd"):
        g["ccd"].append(s["ccd"])
        for sid in s["in_structures"]:
            g["bound_in"].append({"structure": sid, "partners": sorted(owner.get(sid, []))})
        g["sources"].append(f"bound in {', '.join(s['in_structures'])} (component {s['ccd']})")
    else:
        g["sources"].append(f"named in the pack: {s['why']} (curator mapping to PubChem '{s['pubchem_name']}')")
        import re
        for p in re.findall(r"\bP[A-Z]{0,3}\d{2}\b", s["why"]):
            if p in paths and p not in g["paths"]: g["paths"].append(p)
        for ix in re.findall(r"\b(?:ix|d)-[a-z0-9-]+", s["why"]):
            if ix not in g["interactions"]: g["interactions"].append(ix)
for g in groups.values():
    for x in inter:
        if x.get("structure") in {b["structure"] for b in g["bound_in"]} and x["id"] not in g["interactions"]: g["interactions"].append(x["id"])
    hidden = set(g["classes"]) <= {"cofactor", "additive"}
    g["hidden_by_default"] = hidden
    g["bound_in"] = sorted({(b["structure"], tuple(b["partners"])) for b in g["bound_in"]})
    g["bound_in"] = [{"structure": s, "partners": list(p)} for s, p in g["bound_in"]]
    for f_ in g["forms"]:
        if f_["file"] and os.path.exists(os.path.join("content-pack", f_["file"])):
            assert hashlib.sha256(open(os.path.join("content-pack", f_["file"]), "rb").read()).hexdigest() == f_["sha256"], f_
out = {"about": "Small-molecule catalogue (UI-19; app-methods §10). Identity verbatim from PubChem; class is a curator label; conformers are PubChem computed 3D models.",
       "molecules": list(groups.values()), "not_found": missing}
with open("content-pack/small-molecules.yaml", "w", encoding="utf-8") as f:
    f.write("# small-molecules.yaml — generated by tools/build_small_molecules.py. Do not edit.\n")
    yaml.safe_dump(out, f, allow_unicode=True, sort_keys=False, width=110)
c = collections.Counter(g["conformer"] for g in groups.values())
print(f"{len(groups)} small molecules (from {len(harv)} seed entries) · conformers {dict(c)} · not found {len(missing)} · hidden by default {sum(g['hidden_by_default'] for g in groups.values())}")
