#!/usr/bin/env python3
"""build_anatomy.py — Plant Perception Pathways: anatomy.yaml from source/anatomy-seed.yaml and the OLS4 harvest (Plant
Ontology). Cowork-side tool (Actualizer, 2026-11-19), adapted from PPE's. Deterministic. Ontology text is verbatim with
source and date. A pick is kept only if the fetched label or an English synonym matches the name (exact), or the label
contains the name's words (trivially equivalent, e.g. 'pollen tube' → 'pollen tube cell'); the match level is recorded."""
import json, re, html, yaml
seed = yaml.safe_load(open("source/anatomy-seed.yaml", encoding="utf-8"))
h = json.load(open("notes/research/anatomy-harvest.json", encoding="utf-8"))
W = lambda s: set(re.sub(r"s\b", "", w) for w in re.findall(r"[a-z]+", s.lower()))
def syn(r):
    out = []
    for x in r.get("synonyms") or []:
        t = html.unescape(x if isinstance(x, str) else x.get("name") or "")
        m = re.match(r"(.*?) \((exact|broad|narrow|related)\)$", t)
        if m and not re.search(r"[^\x00-\x7f]", m.group(1)) and "Spanish" not in t and "Japanese" not in t: out.append((m.group(1), m.group(2)))
    return out
vals, kept, dropped = [], 0, []
for v in seed["values"]:
    ts = []
    for t in v["terms"]:
        r = h.get(t.get("id") or "", {})
        if not r.get("found"):
            ts.append({"part": t["part"], "id": None, "mapping": "no ontology term mapped"}); continue
        names = [(r["label"], "label")] + syn(r)
        lvl = next((f"exact ({kind})" for n, kind in names if W(n) == W(t["part"]) and kind in ("label", "exact", "broad")), None)
        if not lvl and W(t["part"]) <= W(r["label"]): lvl = "trivially equivalent (label contains the name)"
        if not lvl and W(r["label"]) <= W(t["part"]): lvl = "trivially equivalent (name contains the label)"
        if not lvl:
            dropped.append((t["part"], r["id"], r["label"])); ts.append({"part": t["part"], "id": None, "mapping": f"no ontology term mapped ({r['id']} '{r['label']}' did not match)"}); continue
        kept += 1
        ts.append({"part": t["part"], "id": r["id"], "label": r["label"], "definition": r.get("definition"),
                   "synonyms": [n for n, _ in syn(r)], "parents": r.get("parents") or [], "source": r["source"],
                   "retrieved_on": r["retrieved_on"], "match": lvl, "mapping": f"curator mapping from '{t['part']}'"})
    vals.append({"stage": v["stage"], "value": v["value"], "paths": v["paths"], "terms": ts})
hdr = ("# anatomy.yaml — Plant Ontology (PO) records for anatomical names in the cascade, signal-route and response stage text.\n"
       "# Generated by tools/build_anatomy.py. Labels, definitions, synonyms and parents are verbatim from EBI OLS4. Each term is a\n"
       "# curator mapping from the name in the text; `match` records how the term's label or synonym matches it.\n")
open("content-pack/anatomy.yaml", "w", encoding="utf-8").write(hdr + yaml.safe_dump({"values": vals}, allow_unicode=True, sort_keys=False, width=120))
print(f"{len(vals)} values · {kept} terms kept · dropped {dropped}")
